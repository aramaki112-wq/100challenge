function createCodeMap(definition) {
  if (
    definition === null ||
    typeof definition !== "object" ||
    Array.isArray(definition)
  ) {
    throw new TypeError("Code map definition must be a plain object.");
  }

  return Object.freeze({ ...definition });
}

