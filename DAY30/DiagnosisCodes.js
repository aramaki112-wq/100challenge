export function assertCodeMap(codeMap) {
  if (
    codeMap === null ||
    typeof codeMap !== "object" ||
    Array.isArray(codeMap)
  ) {
    throw new TypeError("codeMap must be a code map object.");
  }

  return codeMap;
}

export function getCodeValues(codeMap) {
  assertCodeMap(codeMap);
  return Object.freeze(Object.values(codeMap));
}

export function isCodeValue(codeMap, value) {
  return getCodeValues(codeMap).includes(value);
}
